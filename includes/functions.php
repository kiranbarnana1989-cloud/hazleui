header('Content-Type: application/json');

try {
    $input = file_get_contents('php://input');
    $data = json_decode($input, true);
    
    if (!isset($data['action'])) {
        throw new Exception('No action specified');
    }

    switch ($data['action']) {
        case 'register':
            $data = json_decode(file_get_contents('php://input'), true);

                // Server-side validation with field-specific errors
                $errors = [];

                if (
                    isset($data['password']) && isset($data['confirm_password']) &&
                    $data['confirm_password'] !== '' &&
                    $data['password'] !== $data['confirm_password']
                ) {
                    $errors['confirm_password'] = ['code' => 'password_mismatch', 'message' => 'Passwords do not match'];
                }

                // Enforce minimum password strength
                if (isset($data['password']) && !isPasswordStrong($data['password'])) {
                    $errors['password'] = ['code' => 'password_weak', 'message' => 'Password must be at least 8 characters and include uppercase, number and special char'];
                }

                // Basic server-side email validation
                if (!isset($data['email']) || !filter_var($data['email'], FILTER_VALIDATE_EMAIL)) {
                    $errors['email'] = ['code' => 'invalid_email', 'message' => 'Invalid email address'];
                } else {
                    // studentId is generated by the database trigger; only check email for duplicates
                    if (isEmailOrStudentIdTaken($data['email'], null)) {
                        $errors['email'] = ['code' => 'email_taken', 'message' => 'Email already registered'];
                    }
                }

                // Phone validation: digits only, 7-15 characters
                if (!isset($data['phone']) || !preg_match('/^[0-9]{7,15}$/', $data['phone'])) {
                    $errors['phone'] = ['code' => 'invalid_phone', 'message' => 'Phone must be 7-15 digits'];
                }

                // Remove confirmation before further processing
                unset($data['confirm_password']);

                if (!empty($errors)) {
                    echo json_encode(['success' => false, 'errors' => $errors]);
                    exit;
                }

            $userData = array_merge($data, [
                'registrationDate' => date('Y-m-d H:i:s'),
                'mockScore' => rand(0, 100),
                'mockRank' => rand(1, 500)
            ]);

            $created = saveUser($userData);
            if ($created) {
                // If saveUser returned the created user row, include it in the response
                if (is_array($created)) {
                    echo json_encode(['success' => true, 'message' => 'Registration successful', 'user' => $created]);
                } else {
                    echo json_encode(['success' => true, 'message' => 'Registration successful']);
                }
            } else {
                echo json_encode(['success' => false, 'message' => 'Registration failed']);
            }
            break;
            
        case 'login':
            $data = json_decode(file_get_contents('php://input'), true);
            
            // Input validation
            if (!isset($data['identifier']) || !isset($data['password'])) {
                echo json_encode([
                    'success' => false, 
                    'message' => 'Missing credentials'
                ]);
                break;
            }

            logError('Login attempt', ['identifier' => $data['identifier']]);
            $user = findUser($data['identifier'], $data['password']);
            
            if ($user) {
                logError('Login successful', ['user' => $user['studentId']]);
                echo json_encode([
                    'success' => true, 
                    'user' => $user,
                    'message' => 'Login successful'
                ]);
            } else {
                logError('Login failed', ['identifier' => $data['identifier']]);
                echo json_encode([
                    'success' => false, 
                    'message' => 'Invalid email/ID or password'
                ]);
            }
            break;
            
        case 'admin_login':
            // Input validation
            if (!isset($data['username']) || !isset($data['password'])) {
                echo json_encode([
                    'success' => false, 
                    'message' => 'Missing credentials'
                ]);
                break;
            }
            
            if (validateAdmin($data['username'], $data['password'])) {
                echo json_encode(['success' => true, 'message' => 'Admin login successful']);
            } else {
                echo json_encode(['success' => false, 'message' => 'Invalid admin credentials']);
            }
            break;
            
        case 'get_users':
            $data = json_decode(file_get_contents('php://input'), true);
            if (isset($data['admin']) && $data['admin'] === true) {
                echo json_encode(['success' => true, 'users' => getUsers()]);
            } else {
                echo json_encode(['success' => false, 'message' => 'Unauthorized']);
            }
            break;
            
        default:
            echo json_encode(['success' => false, 'message' => 'Invalid action']);
    }
} catch (Exception $e) {
    logError($e->getMessage(), isset($data) ? $data : null);
    echo json_encode([
        'success' => false,
        'message' => 'An error occurred: ' . $e->getMessage(),
        'debug' => [
            'input' => isset($input) ? $input : null,
            'parsed' => isset($data) ? $data : null
        ]
    ]);
}
